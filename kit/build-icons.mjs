// Builds every icon for both apps from the drop master: Android launcher
// layers, Play Store, iOS, PWA, favicons, splash and social images. One recipe
// for all of them (drop height as a share of the canvas), so the drop is the
// same size everywhere. Run with `npm run kit` (Docker: node:22).
import fs from 'node:fs';
import path from 'node:path';
import { COLOURS, COLOURWAYS, dropSvg, logoSvg, png } from './build-logo.mjs';

const KIT = path.dirname(new URL(import.meta.url).pathname);
const OUT = path.join(KIT, 'dist');

// The two apps. The customer app is the primary colourway on white; the
// Namamian (staff) app is the reversed colourway on Namami Teal.
const APPS = {
  namamicleans: { ground: COLOURS.white, drop: COLOURWAYS.primary, lockup: 'primary' },
  namamian: { ground: COLOURS.teal, drop: COLOURWAYS.reversed, lockup: 'reversed' },
};

// Drop height as a share of the canvas.
const SHARE = {
  adaptive: 0.44, // Android adaptive foreground: 108dp canvas, launcher shows the centre 72dp
  square: 0.62, // Play Store, iOS, apple-touch: full-bleed square the store/OS rounds
  rounded: 0.58, // PWA "any" and favicons: our own rounded tile
  maskable: 0.5, // PWA maskable: stays inside the 80% safe circle
  splashIcon: 0.4, // Android 12+ splash icon: 288dp canvas, centre 192dp shown
  favicon: 0.7, // browser tabs (16-48 px): a bigger drop so it still reads
  badge: 0.8, // notification badge: a white silhouette, as large as it can be
  splash: 0.28, // full-screen splash: share of the shorter side
};
const TILE_RADIUS = 0.22; // corner radius of our own rounded tiles, share of the side
const MONO = { ...COLOURWAYS.white, body: COLOURS.white, accent: COLOURS.white };

function tile({ size, ground, drop, share, radius = 0 }) {
  const h = size * share;
  const probe = dropSvg(drop, 0, 0, h);
  const d = dropSvg(drop, (size - probe.width) / 2, (size - h) / 2, h);
  const bg = ground ? `<rect width="${size}" height="${size}" rx="${size * radius}" fill="${ground}"/>` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">${bg}${d.svg}</svg>`;
}

function write(file, data) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, data);
}

const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };

// Android adaptive icon XML: full-size layers, no inset (the foreground art
// already sits inside the safe zone).
const ADAPTIVE_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by namami-brand/kit. The foreground keeps the drop inside the
     66dp safe zone, so neither layer is inset. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
`;

function androidIcons(app, spec) {
  const dir = path.join(OUT, '02-app-icons', app, 'android/res');
  for (const [density, scale] of Object.entries(DENSITIES)) {
    const layer = Math.round(108 * scale);
    const legacy = Math.round(48 * scale);
    const m = `mipmap-${density}`;
    write(path.join(dir, m, 'ic_launcher_foreground.png'), png(tile({ size: layer, drop: spec.drop, share: SHARE.adaptive }), layer));
    write(path.join(dir, m, 'ic_launcher_background.png'), png(tile({ size: layer, ground: spec.ground, drop: spec.drop, share: 0 }), layer));
    write(path.join(dir, m, 'ic_launcher_monochrome.png'), png(tile({ size: layer, drop: MONO, share: SHARE.adaptive }), layer));
    // Pre-Android-8 launchers: a ready-made rounded square and a circle.
    write(path.join(dir, m, 'ic_launcher.png'), png(tile({ size: legacy, ground: spec.ground, drop: spec.drop, share: SHARE.rounded, radius: TILE_RADIUS }), legacy));
    write(path.join(dir, m, 'ic_launcher_round.png'), png(tile({ size: legacy, ground: spec.ground, drop: spec.drop, share: SHARE.rounded, radius: 0.5 }), legacy));
  }
  for (const xml of ['ic_launcher.xml', 'ic_launcher_round.xml']) write(path.join(dir, 'mipmap-anydpi-v26', xml), ADAPTIVE_XML);
  write(path.join(dir, 'drawable-nodpi/splash_icon.png'), png(tile({ size: 1152, drop: spec.drop, share: SHARE.splashIcon }), 1152));
}

function storeAndOsIcons(app, spec) {
  const dir = path.join(OUT, '02-app-icons', app);
  const square = tile({ size: 1024, ground: spec.ground, drop: spec.drop, share: SHARE.square });
  write(path.join(dir, `${app}-play-store-512.png`), png(square, 512));
  write(path.join(dir, `${app}-ios-1024.png`), png(square, 1024));
  write(path.join(dir, `${app}-app-icon.svg`), square);
  // Capacitor/@capacitor/assets sources, for regenerating native projects.
  write(path.join(dir, 'capacitor-assets/icon-foreground.png'), png(tile({ size: 1024, drop: spec.drop, share: SHARE.adaptive }), 1024));
  write(path.join(dir, 'capacitor-assets/icon-background.png'), png(tile({ size: 1024, ground: spec.ground, drop: spec.drop, share: 0 }), 1024));
  write(path.join(dir, 'capacitor-assets/icon-monochrome.png'), png(tile({ size: 1024, drop: MONO, share: SHARE.adaptive }), 1024));
  write(path.join(dir, 'capacitor-assets/icon-only.png'), png(square, 1024));
}

// Splash screens: the brand ground with the drop centred.
const SPLASHES = { port: [[320, 480], [480, 800], [720, 1280], [960, 1600], [1280, 1920]], land: [[480, 320], [800, 480], [1280, 720], [1600, 960], [1920, 1280]] };
const SPLASH_DPI = ['ldpi', 'mdpi', 'hdpi', 'xhdpi', 'xxhdpi'];

function splashes(app, spec) {
  const dir = path.join(OUT, '02-app-icons', app, 'android/res');
  const make = (w, h) => {
    const dh = Math.min(w, h) * SHARE.splash;
    const probe = dropSvg(spec.drop, 0, 0, dh);
    const d = dropSvg(spec.drop, (w - probe.width) / 2, (h - dh) / 2, dh);
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}"><rect width="100%" height="100%" fill="${spec.ground}"/>${d.svg}</svg>`;
  };
  for (const [orient, sizes] of Object.entries(SPLASHES)) {
    sizes.forEach(([w, h], i) => write(path.join(dir, `drawable-${orient}-${SPLASH_DPI[i]}/splash.png`), png(make(w, h), w)));
  }
  write(path.join(dir, 'drawable/splash.png'), png(make(480, 320), 480));
}

// favicon.ico holding PNG images (supported by every current browser).
function ico(pngs) {
  const header = Buffer.alloc(6 + 16 * pngs.length);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(pngs.length, 4);
  let offset = header.length;
  pngs.forEach(({ size, data }, i) => {
    const e = 6 + 16 * i;
    header.writeUInt8(size >= 256 ? 0 : size, e);
    header.writeUInt8(size >= 256 ? 0 : size, e + 1);
    header.writeUInt16LE(1, e + 4);
    header.writeUInt16LE(32, e + 6);
    header.writeUInt32LE(data.length, e + 8);
    header.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...pngs.map((p) => p.data)]);
}

function webIcons(app, spec) {
  const dir = path.join(OUT, '03-web-icons', app);
  const rounded = (size) => tile({ size, ground: spec.ground, drop: spec.drop, share: SHARE.rounded, radius: TILE_RADIUS });
  const tab = (size) => tile({ size, ground: spec.ground, drop: spec.drop, share: SHARE.favicon, radius: TILE_RADIUS });
  write(path.join(dir, 'favicon.svg'), tab(64));
  const favicons = [16, 32, 48].map((size) => ({ size, data: png(tab(size * 4), size) }));
  for (const { size, data } of favicons) write(path.join(dir, `favicon-${size}.png`), data);
  write(path.join(dir, 'favicon.ico'), ico(favicons));
  for (const size of [192, 512]) {
    write(path.join(dir, `icon-${size}.png`), png(rounded(size), size));
    write(path.join(dir, `icon-${size}-maskable.png`), png(tile({ size, ground: spec.ground, drop: spec.drop, share: SHARE.maskable }), size));
  }
  write(path.join(dir, 'apple-touch-icon.png'), png(tile({ size: 180, ground: spec.ground, drop: spec.drop, share: SHARE.square }), 180));
  // Notification badge: Android shows only its silhouette in the status bar.
  write(path.join(dir, 'badge-96.png'), png(tile({ size: 96, drop: MONO, share: SHARE.badge }), 96));
}

function social() {
  const dir = path.join(OUT, '04-social');
  const avatar = tile({ size: 800, ground: COLOURS.teal, drop: COLOURWAYS.reversed, share: 0.5 });
  write(path.join(dir, 'namamicleans-avatar-800.png'), png(avatar, 800));
  write(path.join(dir, 'namamicleans-avatar.svg'), avatar);
  const banner = (w, h, lockupWidth) => {
    const lockup = logoSvg('horizontal', 'reversed');
    const [, vw, vh] = lockup.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/).map(Number);
    const lh = (lockupWidth * vh) / vw;
    const inner = lockup.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}"><rect width="100%" height="100%" fill="${COLOURS.teal}"/><svg x="${(w - lockupWidth) / 2}" y="${(h - lh) / 2}" width="${lockupWidth}" height="${lh}" viewBox="0 0 ${vw} ${vh}">${inner}</svg></svg>`;
  };
  const og = banner(1200, 630, 720);
  write(path.join(dir, 'namamicleans-og-1200x630.png'), png(og, 1200));
  write(path.join(dir, 'namamicleans-og-1200x630.svg'), og);
  const cover = banner(1584, 396, 760);
  write(path.join(dir, 'namamicleans-banner-1584x396.png'), png(cover, 1584));
  write(path.join(dir, 'namamicleans-banner-1584x396.svg'), cover);
}

function main() {
  for (const [app, spec] of Object.entries(APPS)) {
    androidIcons(app, spec);
    storeAndOsIcons(app, spec);
    splashes(app, spec);
    webIcons(app, spec);
  }
  social();
  console.log('icons: both apps (Android, Play, iOS, PWA, favicons, splash) + social');
}

main();
